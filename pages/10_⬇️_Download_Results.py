import streamlit as st
import pandas as pd

from knowledge_graph.graph_builder import build_graph
from models.gnn.analyzer import analyze_graph
from models.distillation.distill import distill_graph


st.set_page_config(
    page_title="Download Results | KoGNER",
    page_icon="⬇️",
    layout="wide"
)

st.title("⬇️ Download Results")

st.markdown(
    """
Download the outputs generated by KoGNER for further
analysis or reporting.
"""
)

st.divider()

# -----------------------------------------
# Check Session
# -----------------------------------------

if "biobert_entities" not in st.session_state:

    st.warning(
        "Please run Biomedical NER first."
    )

    st.stop()

entities = st.session_state.biobert_entities

graph = build_graph(entities)

gnn_results = analyze_graph(graph)

distilled_graph, ranked_nodes = distill_graph(
    graph,
    keep_ratio=0.5
)

# -----------------------------------------
# Biomedical Entities
# -----------------------------------------

st.header("🧬 Biomedical Entities")

entities_df = pd.DataFrame(entities)

st.dataframe(
    entities_df,
    use_container_width=True
)

st.download_button(
    label="Download Biomedical Entities (CSV)",
    data=entities_df.to_csv(index=False),
    file_name="biomedical_entities.csv",
    mime="text/csv"
)

st.divider()

# -----------------------------------------
# Knowledge Graph Nodes
# -----------------------------------------

st.header("🕸️ Knowledge Graph Nodes")

nodes = []

for node, attrs in graph.nodes(data=True):

    nodes.append({
        "Entity": node,
        "Type": attrs["entity_type"],
        "Confidence": attrs["confidence"]
    })

nodes_df = pd.DataFrame(nodes)

st.dataframe(
    nodes_df,
    use_container_width=True
)

st.download_button(
    label="Download Graph Nodes (CSV)",
    data=nodes_df.to_csv(index=False),
    file_name="graph_nodes.csv",
    mime="text/csv"
)

st.divider()

# -----------------------------------------
# Knowledge Graph Edges
# -----------------------------------------

st.header("🔗 Knowledge Graph Edges")

edges = []

for source, target, attrs in graph.edges(data=True):

    edges.append({
        "Source": source,
        "Target": target,
        "Relation": attrs["relation"]
    })

edges_df = pd.DataFrame(edges)

st.dataframe(
    edges_df,
    use_container_width=True
)

st.download_button(
    label="Download Graph Edges (CSV)",
    data=edges_df.to_csv(index=False),
    file_name="graph_edges.csv",
    mime="text/csv"
)

st.divider()

# -----------------------------------------
# GNN Statistics
# -----------------------------------------

st.header("📊 GNN Statistics")

gnn_df = pd.DataFrame(
    [
        {
            "Metric": key,
            "Value": str(value)
        }
        for key, value in gnn_results.items()
    ]
)

st.dataframe(
    gnn_df,
    use_container_width=True
)

st.download_button(
    label="Download GNN Statistics (CSV)",
    data=gnn_df.to_csv(index=False),
    file_name="gnn_statistics.csv",
    mime="text/csv"
)

st.divider()

# -----------------------------------------
# Distilled Graph Nodes
# -----------------------------------------

st.header("🧬 Distilled Graph Nodes")

distilled_df = pd.DataFrame({
    "Biomedical Entity": list(
        distilled_graph.nodes()
    )
})

st.dataframe(
    distilled_df,
    use_container_width=True
)

st.download_button(
    label="Download Distilled Graph (CSV)",
    data=distilled_df.to_csv(index=False),
    file_name="distilled_graph.csv",
    mime="text/csv"
)